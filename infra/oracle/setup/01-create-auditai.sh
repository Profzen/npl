#!/usr/bin/env bash
set -euo pipefail

: "${AUDITAI_OWNER_PASSWORD:?AUDITAI_OWNER_PASSWORD absent}"
: "${AUDITAI_READER_PASSWORD:?AUDITAI_READER_PASSWORD absent}"

sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;

CREATE USER SMART2DSECU IDENTIFIED BY "${AUDITAI_OWNER_PASSWORD}";
ALTER USER SMART2DSECU QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE TO SMART2DSECU;

CREATE USER AUDITAI_READER IDENTIFIED BY "${AUDITAI_READER_PASSWORD}";
GRANT CREATE SESSION TO AUDITAI_READER;

CREATE TABLE SMART2DSECU.UNIFIED_AUDIT_DATA (
    ID                  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AUDIT_TYPE          VARCHAR2(30) NOT NULL,
    SESSIONID           NUMBER,
    OS_USERNAME         VARCHAR2(128),
    USERHOST            VARCHAR2(255),
    TERMINAL            VARCHAR2(128),
    AUTHENTICATION_TYPE VARCHAR2(64),
    DBUSERNAME          VARCHAR2(128),
    CLIENT_PROGRAM_NAME VARCHAR2(255),
    OBJECT_SCHEMA       VARCHAR2(128),
    OBJECT_NAME         VARCHAR2(128),
    SQL_TEXT            VARCHAR2(2000),
    SQL_BINDS           VARCHAR2(2000),
    EVENT_TIMESTAMP     TIMESTAMP(6) NOT NULL,
    ACTION_NAME         VARCHAR2(128) NOT NULL,
    RETURNCODE          NUMBER DEFAULT 0 NOT NULL,
    INSTANCE            NUMBER DEFAULT 1 NOT NULL
);

CREATE INDEX SMART2DSECU.IX_AUDIT_TIME
    ON SMART2DSECU.UNIFIED_AUDIT_DATA (EVENT_TIMESTAMP);
CREATE INDEX SMART2DSECU.IX_AUDIT_USER
    ON SMART2DSECU.UNIFIED_AUDIT_DATA (DBUSERNAME);
CREATE INDEX SMART2DSECU.IX_AUDIT_OBJECT
    ON SMART2DSECU.UNIFIED_AUDIT_DATA (OBJECT_NAME);
CREATE INDEX SMART2DSECU.IX_AUDIT_ACTION
    ON SMART2DSECU.UNIFIED_AUDIT_DATA (ACTION_NAME);

CREATE TABLE SMART2DSECU.AUDITAI_SEMANTIC_CATALOG (
    CATEGORY       VARCHAR2(30) NOT NULL,
    CANONICAL_NAME VARCHAR2(128) NOT NULL,
    DESCRIPTION_FR VARCHAR2(500) NOT NULL,
    SYNONYMS_FR    VARCHAR2(1000),
    CONSTRAINT PK_AUDITAI_SEMANTIC_CATALOG PRIMARY KEY (CATEGORY, CANONICAL_NAME)
);

INSERT ALL
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','SELECT','Consultation ou lecture de données','consulte, lu, regarde, affiche, accede')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','INSERT','Ajout de nouvelles données','insere, ajoute, cree une ligne')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','UPDATE','Modification de données existantes','modifie, change, corrige, met a jour')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','DELETE','Suppression de lignes','supprime, efface, retire')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','GRANT','Attribution d un privilège','donne un droit, accorde, autorise')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','REVOKE','Retrait d un privilège','retire un droit, revoque')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','ALTER','Modification de structure ou de compte','change la structure, modifie le compte')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','TRUNCATE','Suppression de toutes les lignes d une table','vide la table, purge la table')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','LOGON','Ouverture d une session Oracle','connexion, login, se connecte')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('ACTION','LOGOFF','Fermeture d une session Oracle','deconnexion, logout, quitte la session')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('TIME','EVENT_TIMESTAMP','Date et heure auxquelles l événement a eu lieu','hier, aujourd hui, vendredi, semaine, mois, entre')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('USER','DBUSERNAME','Utilisateur Oracle ayant réalisé l action','user, utilisateur, compte, qui')
  INTO SMART2DSECU.AUDITAI_SEMANTIC_CATALOG VALUES ('OBJECT','OBJECT_NAME','Table ou objet Oracle concerné','table, objet, donnée, ressource')
SELECT 1 FROM DUAL;

INSERT INTO SMART2DSECU.UNIFIED_AUDIT_DATA (
    AUDIT_TYPE, SESSIONID, OS_USERNAME, USERHOST, TERMINAL,
    AUTHENTICATION_TYPE, DBUSERNAME, CLIENT_PROGRAM_NAME,
    OBJECT_SCHEMA, OBJECT_NAME, SQL_TEXT, SQL_BINDS,
    EVENT_TIMESTAMP, ACTION_NAME, RETURNCODE, INSTANCE
)
SELECT
    CASE MOD(n, 2) WHEN 0 THEN 'UNIFIED' ELSE 'STANDARD' END,
    100000 + n,
    CASE MOD(n, 5) WHEN 0 THEN 'oracle' WHEN 1 THEN 'system' WHEN 2 THEN 'cyrille' WHEN 3 THEN 'batch' ELSE 'audit' END,
    CASE MOD(n, 5) WHEN 0 THEN 'srv-oracle-01' WHEN 1 THEN 'app-server-01' WHEN 2 THEN 'poste-rh-07' WHEN 3 THEN 'laptop-cyrille' ELSE 'srv-batch-02' END,
    'pts/' || MOD(n, 10),
    CASE MOD(n, 4) WHEN 0 THEN 'PASSWORD' WHEN 1 THEN 'KERBEROS' WHEN 2 THEN 'CERTIFICATE' ELSE 'NONE' END,
    CASE MOD(n, 14)
      WHEN 0 THEN 'SYS' WHEN 1 THEN 'SYSTEM' WHEN 2 THEN 'CYRILLE'
      WHEN 3 THEN 'CYRILLE_TBS' WHEN 4 THEN 'ITEST' WHEN 5 THEN 'HR'
      WHEN 6 THEN 'SMART2DADMIN' WHEN 7 THEN 'SMART2DADMINI'
      WHEN 8 THEN 'BATCH_USER' WHEN 9 THEN 'PROD2_MDS' WHEN 10 THEN 'PROD2_STB'
      WHEN 11 THEN 'AUDIT_MANAGER' WHEN 12 THEN 'REPORT_USER' ELSE 'NEW_USER_APP' END,
    CASE MOD(n, 6) WHEN 0 THEN 'sqlplus' WHEN 1 THEN 'TOAD' WHEN 2 THEN 'JDBC' WHEN 3 THEN 'Python' WHEN 4 THEN 'PowerBI' ELSE 'AuditAI' END,
    CASE MOD(n, 4) WHEN 0 THEN 'HR' WHEN 1 THEN 'SYS' WHEN 2 THEN 'SMART2DSECU' ELSE 'APP_SCHEMA' END,
    CASE WHEN action_name IN ('LOGON','LOGOFF','CREATE USER','DROP USER','ALTER USER') THEN NULL ELSE object_name END,
    CASE WHEN action_name IN ('LOGON','LOGOFF') THEN NULL ELSE '/* simulation locale */ ' || action_name || ' ON ' || object_name END,
    NULL,
    SYSTIMESTAMP - NUMTODSINTERVAL(MOD(n * 37, 129600), 'MINUTE'),
    action_name,
    CASE WHEN MOD(n, 23) = 0 THEN CASE MOD(n, 3) WHEN 0 THEN 1017 WHEN 1 THEN 1031 ELSE 904 END ELSE 0 END,
    1
FROM (
    SELECT LEVEL n,
           CASE MOD(LEVEL, 16)
             WHEN 0 THEN 'LOGON' WHEN 1 THEN 'LOGOFF' WHEN 2 THEN 'SELECT'
             WHEN 3 THEN 'INSERT' WHEN 4 THEN 'UPDATE' WHEN 5 THEN 'DELETE'
             WHEN 6 THEN 'GRANT' WHEN 7 THEN 'REVOKE' WHEN 8 THEN 'ALTER'
             WHEN 9 THEN 'CREATE USER' WHEN 10 THEN 'DROP USER' WHEN 11 THEN 'ALTER USER'
             WHEN 12 THEN 'CREATE TABLE' WHEN 13 THEN 'DROP TABLE'
             WHEN 14 THEN 'TRUNCATE' ELSE 'SELECT' END action_name,
           CASE MOD(LEVEL, 15)
             WHEN 0 THEN 'EMPLOYEES' WHEN 1 THEN 'DEPARTMENTS' WHEN 2 THEN 'HR'
             WHEN 3 THEN 'ADRESS' WHEN 4 THEN 'CLIENT' WHEN 5 THEN 'FACTURES'
             WHEN 6 THEN 'COMMANDES' WHEN 7 THEN 'PAIEMENTS' WHEN 8 THEN 'CONTRATS'
             WHEN 9 THEN 'SALARIES' WHEN 10 THEN 'FOURNISSEURS' WHEN 11 THEN 'DOSSIERS'
             WHEN 12 THEN 'UTILISATEURS' WHEN 13 THEN 'NOUVELLE_TABLE_METIER'
             ELSE 'AUDIT_LOG' END object_name
    FROM DUAL CONNECT BY LEVEL <= 5000
);

INSERT INTO SMART2DSECU.UNIFIED_AUDIT_DATA
  (AUDIT_TYPE, SESSIONID, OS_USERNAME, USERHOST, TERMINAL, AUTHENTICATION_TYPE,
   DBUSERNAME, CLIENT_PROGRAM_NAME, OBJECT_SCHEMA, OBJECT_NAME, SQL_TEXT,
   EVENT_TIMESTAMP, ACTION_NAME, RETURNCODE, INSTANCE)
VALUES
  ('UNIFIED', 900001, 'cyrille', 'poste-rh-07', 'pts/2', 'PASSWORD',
   'CYRILLE', 'TOAD', 'HR', 'CLIENT', 'DELETE FROM CLIENT WHERE ID_CLIENT=42',
   TRUNC(SYSTIMESTAMP) - INTERVAL '1' DAY + INTERVAL '14' HOUR, 'DELETE', 0, 1);

INSERT INTO SMART2DSECU.UNIFIED_AUDIT_DATA
  (AUDIT_TYPE, SESSIONID, OS_USERNAME, USERHOST, TERMINAL, AUTHENTICATION_TYPE,
   DBUSERNAME, CLIENT_PROGRAM_NAME, OBJECT_SCHEMA, OBJECT_NAME, SQL_TEXT,
   EVENT_TIMESTAMP, ACTION_NAME, RETURNCODE, INSTANCE)
VALUES
  ('UNIFIED', 900002, 'system', 'srv-oracle-01', 'pts/0', 'PASSWORD',
   'SYSTEM', 'sqlplus', 'HR', 'EMPLOYEES', 'GRANT SELECT ON HR.EMPLOYEES TO REPORT_USER',
   TRUNC(SYSTIMESTAMP) + INTERVAL '9' HOUR, 'GRANT', 0, 1);

INSERT INTO SMART2DSECU.UNIFIED_AUDIT_DATA
  (AUDIT_TYPE, SESSIONID, OS_USERNAME, USERHOST, TERMINAL, AUTHENTICATION_TYPE,
   DBUSERNAME, CLIENT_PROGRAM_NAME, OBJECT_SCHEMA, OBJECT_NAME, SQL_TEXT,
   EVENT_TIMESTAMP, ACTION_NAME, RETURNCODE, INSTANCE)
VALUES
  ('UNIFIED', 900003, 'report', 'app-server-01', 'pts/4', 'PASSWORD',
   'REPORT_USER', 'JDBC', 'HR', 'EMPLOYEES', 'SELECT * FROM HR.EMPLOYEES',
   TRUNC(SYSDATE, 'IW') - 3 + INTERVAL '10' HOUR, 'SELECT', 0, 1);

COMMIT;

GRANT SELECT ON SMART2DSECU.UNIFIED_AUDIT_DATA TO AUDITAI_READER;
GRANT SELECT ON SMART2DSECU.AUDITAI_SEMANTIC_CATALOG TO AUDITAI_READER;
SQL

echo "AuditAI : schéma SMART2DSECU, lecteur AUDITAI_READER et 5003 événements créés."

